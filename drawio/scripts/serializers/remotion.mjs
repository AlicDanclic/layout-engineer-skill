#!/usr/bin/env node
/**
 * serializer: remotion — Layout Tree + Storyboard 时间轴 -> Remotion 合成组件。
 *
 * **铁律：零几何计算。** 坐标只做字段映射（`left: node.x`），
 * Remotion 合成的 width/height 就是画布尺寸，所以像素坐标可以原样使用。
 * 入场动画的位移量取自 timeline.json 的 `offset`（不是代码里的字面量），
 * 本文件只做 `1 - progress` 的插值，不参与布局几何。
 *
 * 每个节点挂 `data-layout-id` / `data-expr`，便于在 Remotion Studio 里逐节点回溯。
 *
 * 用法：node scripts/serializers/remotion.mjs --project <dir> [--breakpoint desktop]
 */
import path from "node:path";
import fs from "node:fs";
import { listTrees, ensureDir, readJson } from "../../../layout/scripts/layout-engine/io.mjs";
import { requireConfirmation, allowUnconfirmed, scopeFrom, previewPath } from "./gate.mjs";

const indent = (obj) =>
  JSON.stringify(obj, null, 2)
    .split("\n")
    .map((l) => "  " + l)
    .join("\n");

export function renderRemotion(tree, timeline, projectName) {
  const comp = projectName.replace(/[^A-Za-z0-9_$]/g, "_").replace(/^(\d)/, "_$1");
  const tracks = timeline?.tracks ?? [];
  const duration = timeline?.durationInFrames ?? 90;
  const fps = timeline?.fps ?? 30;

  return `// AUTO-GENERATED by layout-engineer/serializers/remotion.mjs —— 请勿手改。
// 铁律：零几何计算。坐标来自 Layout Tree，动画位移量来自 timeline.json 的 offset。
/* eslint-disable */
import React from "react";
import { AbsoluteFill, Sequence, interpolate, useCurrentFrame, useVideoConfig } from "remotion";

const CANVAS = ${indent(tree.canvas)};
const TREE = ${indent(tree)};

type Anim = "none" | "fade" | "slide-up" | "slide-left" | "scale";

const TRACKS: Record<
  string,
  { from: number; durationInFrames: number; animation: Anim; offset: number }
> = ${indent(
    Object.fromEntries(
      tracks.map((t) => [
        t.id,
        {
          from: t.from,
          durationInFrames: t.durationInFrames,
          animation: t.animation ?? "fade",
          offset: t.offset ?? 0,
        },
      ]),
    ),
  )};

function animStyle(anim: Anim, progress: number, offset: number): React.CSSProperties {
  const rest = 1 - progress;
  switch (anim) {
    case "fade":
      return { opacity: progress };
    case "slide-up":
      return { opacity: progress, transform: "translateY(" + rest * offset + "px)" };
    case "slide-left":
      return { opacity: progress, transform: "translateX(" + rest * offset + "px)" };
    case "scale":
      return { opacity: progress, transform: "scale(" + (1 - rest) + ")" };
    default:
      return {};
  }
}

function NodeView({ node }: { node: any }) {
  const frame = useCurrentFrame();
  const { durationInFrames } = useVideoConfig();
  const track = TRACKS[node.id];
  const start = track ? track.from : 0;
  const len = track ? track.durationInFrames : durationInFrames;
  const progress = track
    ? interpolate(frame, [start, start + Math.max(1, Math.round(len * 0.4))], [0, 1], {
        extrapolateLeft: "clamp",
        extrapolateRight: "clamp",
      })
    : 1;
  return (
    <div
      data-layout-id={node.id}
      data-expr={JSON.stringify(node.expr)}
      style={{
        position: "absolute",
        left: node.x,
        top: node.y,
        width: node.w,
        height: node.h,
        boxSizing: "border-box",
        ...animStyle(track?.animation ?? "none", progress, track?.offset ?? 0),
      }}
    >
      {(node.children ?? []).map((c: any) => (
        <NodeView key={c.id} node={c} />
      ))}
    </div>
  );
}

/**
 * Remotion 合成组件
 *
 * @returns 按时间轴播放的绝对定位画面
 *
 * 功能：把 Layout Tree 与关键帧时间轴序列化为 Remotion 合成。
 * 实现原理：只做字段映射与入场插值；TRACKS 的 from/duration/offset 全部来自
 *           storyboard 产出的 timeline.json，代码里没有任何几何字面量。
 */
export function ${comp}Composition() {
  return (
    <AbsoluteFill style={{ backgroundColor: "#ffffff", width: CANVAS.w, height: CANVAS.h }}>
      {TREE.elements.map((n: any) => {
        const track = TRACKS[n.id];
        if (!track) return <NodeView key={n.id} node={n} />;
        return (
          <Sequence key={n.id} from={track.from} durationInFrames={track.durationInFrames}>
            <NodeView node={n} />
          </Sequence>
        );
      })}
    </AbsoluteFill>
  );
}

export const ${comp}Meta = {
  id: ${JSON.stringify(comp)},
  component: ${comp}Composition,
  durationInFrames: ${duration},
  fps: ${fps},
  width: CANVAS.w,
  height: CANVAS.h,
};
`;
}

async function main() {
  const argv = process.argv.slice(2);
  const pi = argv.indexOf("--project");
  const project = path.resolve(pi >= 0 ? argv[pi + 1] : ".");
  const bi = argv.indexOf("--breakpoint");
  const bpArg = bi >= 0 ? argv[bi + 1] : null;

  const trees = Object.fromEntries(
    listTrees(path.join(project, "layout-tree")).map(([, t]) => [t.canvas.breakpoint, t]),
  );
  const bp = bpArg ?? (trees.desktop ? "desktop" : Object.keys(trees)[0]);
  if (!bp || !trees[bp]) throw new Error("layout-tree/ 下没有可用的 Layout Tree");
  // 视频与静态产物闸门分开：这里读的是 timeline 指纹
  const allow = allowUnconfirmed(argv);
  requireConfirmation(project, "storyboard", { allow, scope: scopeFrom(argv) });

  const timelinePath = path.join(project, "positioning", "storyboard", "timeline.json");
  const timeline = fs.existsSync(timelinePath) ? readJson(timelinePath) : null;

  const outDir = path.join(project, "src", "serializers");
  ensureDir(outDir);
  const file = previewPath(path.join(outDir, "Composition.tsx"), allow);
  fs.writeFileSync(file, renderRemotion(trees[bp], timeline, path.basename(project)));
  console.log(
    `✓ remotion serializer → ${path.relative(project, file)}` +
      (timeline ? `（时间轴 ${timeline.durationInFrames} 帧）` : "（无时间轴，常驻画面）"),
  );
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  Promise.resolve()
    .then(main)
    .catch((e) => {
      // 闸门类错误只打印一行提示，不抛堆栈
      console.error(e?.isGateError ? `\n✗ ${e.message}` : (e?.stack ?? String(e)));
      process.exit(1);
    });
}
