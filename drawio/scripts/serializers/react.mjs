#!/usr/bin/env node
/**
 * serializer: react — Layout Tree -> React/JSX 组件。
 *
 * **铁律：零几何计算。**
 * 本文件（以及它产出的代码）只把树里的 x/y/w/h 原样放进 width/height/left/top，
 * 不出现任何 `+10`、`*0.5`。一旦允许几何运算，就存在「树里标的 88、渲染出来是 90」
 * 的缝隙，前面所有确认流程的意义都会被架空。
 *
 * 等比缩放不在 JS 里做：容器固定为画布尺寸，由宿主设置 CSS 变量 `--layout-scale`
 * （`transform: scale(var(--layout-scale, 1))`）。
 *
 * 每个节点挂 `data-layout-id` 与 `data-expr`，成品在浏览器里可逐节点回溯到树与算式。
 *
 * 用法：node scripts/serializers/react.mjs --project <dir>
 */
import path from "node:path";
import fs from "node:fs";
import { listTrees, ensureDir } from "../../../layout/scripts/layout-engine/io.mjs";
import { requireConfirmation, allowUnconfirmed, scopeFrom, previewPath } from "./gate.mjs";

const indent = (obj) =>
  JSON.stringify(obj, null, 2)
    .split("\n")
    .map((l) => "  " + l)
    .join("\n");

export function renderReact(trees, scope = null) {
  const bps = Object.keys(trees).filter((bp) => !scope || scope.includes(bp));
  if (bps.length === 0) throw new Error(`交付范围 ${scope.join("/")} 内没有可用的 Layout Tree`);
  const fallback = bps.includes("desktop") ? "desktop" : bps[0];
  const frame = trees[fallback].canvas;
  return `// AUTO-GENERATED by layout-engineer/serializers/react.mjs —— 请勿手改，改动会被覆盖。
// 数据来源：layout-tree/*.json（Layout Tree 是唯一的几何事实来源）
// 本文件不做任何几何计算，只把 x/y/w/h 原样映射到 CSS 属性。
/* eslint-disable */
import React, { useEffect, useState } from "react";

export type Breakpoint = ${bps.map((b) => JSON.stringify(b)).join(" | ")};

const TREES: Record<Breakpoint, any> = {
${bps.map((bp) => `  ${bp}: ${indent(trees[bp])},`).join("\n")}
};

function useBreakpoint(): Breakpoint {
  const [bp, setBp] = useState<Breakpoint>(${JSON.stringify(fallback)});
  useEffect(() => {
    const mq = window.matchMedia("(min-width: 768px)");
    const apply = () => setBp(mq.matches ? "desktop" : "mobile");
    apply();
    mq.addEventListener("change", apply);
    return () => mq.removeEventListener("change", apply);
  }, []);
  return bp;
}

function NodeView({ node }: { node: any }) {
  return (
    <div
      data-layout-id={node.id}
      data-layout-label={node.label}
      data-expr={JSON.stringify(node.expr)}
      style={{
        position: "absolute",
        left: node.x,
        top: node.y,
        width: node.w,
        height: node.h,
        boxSizing: "border-box",
      }}
    >
      {(node.children ?? []).map((c: any) => (
        <NodeView key={c.id} node={c} />
      ))}
    </div>
  );
}

/**
 * 布局组件
 *
 * @param breakpoint 可选，强制断点；缺省时按视口宽度自动切换
 * @param className 可选，透传给外层容器
 * @returns 绝对定位的页面骨架
 *
 * 功能：把 Layout Tree 序列化为 DOM，坐标取自 layout-tree/*.json。
 * 实现原理：只做字段映射，不做几何运算；容器固定为画布尺寸，
 *           等比缩放交给宿主通过 CSS 变量 --layout-scale 控制。
 */
export function Layout({ breakpoint, className }: { breakpoint?: Breakpoint; className?: string }) {
  const auto = useBreakpoint();
  const bp = breakpoint ?? auto;
  const tree = TREES[bp];
  const canvas = tree.canvas;
  return (
    <div
      className={className}
      data-layout-breakpoint={bp}
      style={{
        position: "relative",
        width: canvas.w,
        height: canvas.h,
        transformOrigin: "top left",
        transform: "scale(var(--layout-scale, 1))",
        overflow: "hidden",
      }}
    >
      {tree.elements.map((n: any) => (
        <NodeView key={n.id} node={n} />
      ))}
    </div>
  );
}

export const CANVAS = ${JSON.stringify(
    Object.fromEntries(bps.map((bp) => [bp, trees[bp].canvas])),
    null,
    2,
  )};

export default Layout;
`;
}

async function main() {
  const argv = process.argv.slice(2);
  const pi = argv.indexOf("--project");
  const project = path.resolve(pi >= 0 ? argv[pi + 1] : ".");
  const scope = scopeFrom(argv);
  const trees = Object.fromEntries(
    listTrees(path.join(project, "layout-tree"))
      .filter(([, t]) => !scope || scope.includes(t.canvas.breakpoint))
      .map(([, t]) => [t.canvas.breakpoint, t]),
  );
  if (!Object.keys(trees).length) throw new Error("layout-tree/ 下没有 Layout Tree，请先运行 build-tree.mjs");
  const allow = allowUnconfirmed(argv);
  requireConfirmation(project, "static", { allow, scope });
  const outDir = path.join(project, "src", "serializers");
  ensureDir(outDir);
  const file = previewPath(path.join(outDir, "Layout.tsx"), allow);
  fs.writeFileSync(file, renderReact(trees, scope));
  console.log(`✓ react serializer → ${path.relative(project, file)}`);
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  Promise.resolve()
    .then(main)
    .catch((e) => {
      // 闸门类错误只打印一行提示，不抛堆栈
      console.error(e?.isGateError ? `\n✗ ${e.message}` : (e?.stack ?? String(e)));
      process.exit(1);
    });
}
